import cn.hutool.core.date.DateUtil;
import cn.hutool.core.io.FileUtil;
import cn.hutool.core.util.StrUtil;
import cn.hutool.json.JSONArray;
import cn.hutool.json.JSONUtil;
import com.baomidou.mybatisplus.core.conditions.query.LambdaQueryWrapper;
import com.baomidou.mybatisplus.extension.service.impl.ServiceImpl;
import com.zmt.picturebackendpro.exception.BusinessException;
import com.zmt.picturebackendpro.exception.ErrorCode;
import com.zmt.picturebackendpro.manager.auth.StpKit;
import com.zmt.picturebackendpro.model.dto.user.VipCode;
import com.zmt.picturebackendpro.model.entity.User;

import com.zmt.picturebackendpro.mapper.UserMapper;
import com.zmt.picturebackendpro.model.enums.UserRoleEnum;
import com.zmt.picturebackendpro.model.vo.LoginUserVO;
import com.zmt.picturebackendpro.model.vo.UserVO;
import com.zmt.picturebackendpro.service.UserService;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
